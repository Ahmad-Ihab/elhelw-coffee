create or replace function public.admin_receive_supplier_purchase(p_purchase_order_id uuid, p_items jsonb, p_supplier_invoice_number text default null)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_item jsonb;
  v_line public.supplier_purchase_order_items%rowtype;
  v_qty numeric(14,3);
  v_received numeric(14,3) := 0;
  v_remaining integer;
begin
  if not public.is_admin() then raise exception 'غير مصرح: صلاحيات الإدارة مطلوبة'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'يجب تحديد كميات الاستلام';
  end if;

  perform 1 from public.supplier_purchase_orders where id = p_purchase_order_id for update;
  if not found then raise exception 'الطلبية غير موجودة'; end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    select * into v_line from public.supplier_purchase_order_items
    where id = (v_item->>'item_id')::uuid and purchase_order_id = p_purchase_order_id for update;
    if not found then raise exception 'بند غير صحيح في الطلبية'; end if;
    v_qty := (v_item->>'quantity_kg')::numeric;
    if v_qty is null or v_qty <= 0 or v_line.received_quantity_kg + v_qty > v_line.ordered_quantity_kg then
      raise exception 'كمية الاستلام غير صحيحة أو تتجاوز الكمية المطلوبة';
    end if;
    update public.supplier_purchase_order_items
      set received_quantity_kg = received_quantity_kg + v_qty
      where id = v_line.id;
    insert into public.raw_material_stock_movements(raw_material_id,movement_type,quantity_kg,reference_type,reference_id,notes,created_by)
      values(v_line.raw_material_id,'receipt',v_qty,'supplier_purchase_order',p_purchase_order_id,'استلام طلبية مورد',auth.uid());
    v_received := v_received + v_qty;
  end loop;

  if p_supplier_invoice_number is not null then
    update public.supplier_purchase_orders set supplier_invoice_number = p_supplier_invoice_number, updated_at = now()
      where id = p_purchase_order_id;
  end if;

  select count(*) into v_remaining from public.supplier_purchase_order_items
    where purchase_order_id = p_purchase_order_id and received_quantity_kg < ordered_quantity_kg;
  update public.supplier_purchase_orders
    set status = case when v_remaining = 0 then 'received' else 'partially_received' end, updated_at = now()
    where id = p_purchase_order_id;

  return jsonb_build_object('received_kg',v_received,'status',case when v_remaining = 0 then 'received' else 'partially_received' end);
end;
$$;

create or replace function public.admin_issue_raw_materials(p_items jsonb, p_reference text default null, p_notes text default null)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_item jsonb;
  v_material uuid;
  v_qty numeric(14,3);
  v_balance numeric(14,3);
  v_issued numeric(14,3) := 0;
begin
  if not public.is_admin() then raise exception 'غير مصرح: صلاحيات الإدارة مطلوبة'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'يجب تحديد الخامات المصروفة';
  end if;
  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_material := (v_item->>'raw_material_id')::uuid;
    v_qty := (v_item->>'quantity_kg')::numeric;
    if v_qty is null or v_qty <= 0 then raise exception 'كمية الصرف غير صحيحة'; end if;
    insert into public.raw_material_stock_balances(raw_material_id,quantity_kg)
      values(v_material,0) on conflict (raw_material_id) do nothing;
    select quantity_kg into v_balance from public.raw_material_stock_balances
      where raw_material_id = v_material for update;
    if v_balance < v_qty then
      raise exception 'الرصيد غير كافٍ للخامة %: المتاح % كجم والمطلوب % كجم',v_material,v_balance,v_qty;
    end if;
    insert into public.raw_material_stock_movements(raw_material_id,movement_type,quantity_kg,reference_type,notes,created_by)
      values(v_material,'production_issue',v_qty,'production',p_notes,auth.uid());
    v_issued := v_issued + v_qty;
  end loop;
  return jsonb_build_object('issued_kg',v_issued,'reference',p_reference);
end;
$$;

create or replace function public.admin_adjust_raw_material_stock(p_raw_material_id uuid, p_quantity_kg numeric, p_direction text, p_notes text default null)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare v_balance numeric(14,3);
begin
  if not public.is_admin() then raise exception 'غير مصرح: صلاحيات الإدارة مطلوبة'; end if;
  if p_quantity_kg is null or p_quantity_kg <= 0 or p_direction not in ('in','out') then
    raise exception 'بيانات التسوية غير صحيحة';
  end if;
  insert into public.raw_material_stock_balances(raw_material_id,quantity_kg)
    values(p_raw_material_id,0) on conflict (raw_material_id) do nothing;
  select quantity_kg into v_balance from public.raw_material_stock_balances
    where raw_material_id=p_raw_material_id for update;
  if p_direction='out' and v_balance < p_quantity_kg then raise exception 'الرصيد غير كافٍ'; end if;
  insert into public.raw_material_stock_movements(raw_material_id,movement_type,quantity_kg,notes,created_by)
    values(p_raw_material_id,case when p_direction='in' then 'adjustment_in' else 'adjustment_out' end,p_quantity_kg,p_notes,auth.uid());
end;
$$;

create or replace function public.apply_raw_material_stock_movement()
returns trigger language plpgsql security definer set search_path = pg_catalog, public
as $$
declare v_delta numeric(14,3);
begin
  v_delta := case when new.movement_type in ('receipt','adjustment_in') then new.quantity_kg else -new.quantity_kg end;
  insert into public.raw_material_stock_balances(raw_material_id,quantity_kg,updated_at)
    values(new.raw_material_id,greatest(v_delta,0),now())
    on conflict (raw_material_id) do update
      set quantity_kg = public.raw_material_stock_balances.quantity_kg + v_delta,
          updated_at = now();
  if (select quantity_kg from public.raw_material_stock_balances where raw_material_id=new.raw_material_id) < 0 then
    raise exception 'رصيد الخامة لا يسمح بهذه الحركة';
  end if;
  return new;
end;
$$;

drop trigger if exists raw_material_stock_movement_apply on public.raw_material_stock_movements;
create trigger raw_material_stock_movement_apply
after insert on public.raw_material_stock_movements
for each row execute function public.apply_raw_material_stock_movement();

