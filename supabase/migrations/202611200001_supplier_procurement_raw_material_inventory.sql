-- Supplier purchasing, editable production recipes, and raw-material inventory.
create table if not exists public.suppliers (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  contact_name text,
  phone text,
  notes text,
  active boolean not null default true,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.raw_materials (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  unit text not null default 'kg' check (unit in ('kg','g','liter','piece')),
  active boolean not null default true,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.supplier_material_prices (
  id uuid primary key default gen_random_uuid(),
  supplier_id uuid not null references public.suppliers(id) on delete restrict,
  raw_material_id uuid not null references public.raw_materials(id) on delete restrict,
  unit_price numeric(14,3) not null check (unit_price >= 0),
  updated_at timestamptz not null default now(),
  unique (supplier_id, raw_material_id)
);

create table if not exists public.production_recipes (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  description text,
  roast_loss_percent numeric(5,2) not null default 20 check (roast_loss_percent >= 0 and roast_loss_percent < 100),
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.production_recipe_items (
  id uuid primary key default gen_random_uuid(),
  recipe_id uuid not null references public.production_recipes(id) on delete cascade,
  raw_material_id uuid not null references public.raw_materials(id) on delete restrict,
  output_kg_per_kg numeric(12,6) not null check (output_kg_per_kg > 0),
  apply_roast_loss boolean not null default false,
  unique (recipe_id, raw_material_id)
);

create table if not exists public.raw_material_stock_balances (
  raw_material_id uuid primary key references public.raw_materials(id) on delete restrict,
  quantity_kg numeric(14,3) not null default 0 check (quantity_kg >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists public.raw_material_stock_movements (
  id uuid primary key default gen_random_uuid(),
  raw_material_id uuid not null references public.raw_materials(id) on delete restrict,
  movement_type text not null check (movement_type in ('receipt','production_issue','adjustment_in','adjustment_out')),
  quantity_kg numeric(14,3) not null check (quantity_kg > 0),
  reference_type text,
  reference_id uuid,
  notes text,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create table if not exists public.supplier_purchase_orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  supplier_id uuid not null references public.suppliers(id) on delete restrict,
  status text not null default 'draft' check (status in ('draft','ordered','partially_received','received','cancelled')),
  order_date date not null default current_date,
  expected_date date,
  supplier_invoice_number text,
  notes text,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.supplier_purchase_order_items (
  id uuid primary key default gen_random_uuid(),
  purchase_order_id uuid not null references public.supplier_purchase_orders(id) on delete cascade,
  raw_material_id uuid not null references public.raw_materials(id) on delete restrict,
  ordered_quantity_kg numeric(14,3) not null check (ordered_quantity_kg > 0),
  received_quantity_kg numeric(14,3) not null default 0 check (received_quantity_kg >= 0 and received_quantity_kg <= ordered_quantity_kg),
  unit_price numeric(14,3) not null check (unit_price >= 0),
  unique (purchase_order_id, raw_material_id)
);

create index if not exists supplier_material_prices_material_idx on public.supplier_material_prices(raw_material_id);
create index if not exists raw_material_movements_material_date_idx on public.raw_material_stock_movements(raw_material_id, created_at desc);
create index if not exists supplier_purchase_orders_supplier_date_idx on public.supplier_purchase_orders(supplier_id, order_date desc);
create index if not exists supplier_purchase_items_order_idx on public.supplier_purchase_order_items(purchase_order_id);

