-- Elhelw Coffee Distributor Management
-- PostgreSQL / Supabase schema. Run in a NEW Supabase project.
create extension if not exists pgcrypto;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role text not null check (role in ('admin','distributor')),
  created_at timestamptz not null default now()
);

create table public.distributors (
  id uuid primary key default gen_random_uuid(),
  user_id uuid unique not null references public.profiles(id),
  name text not null,
  phone text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.products (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  unit text not null default 'kg',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.product_prices (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products(id),
  price numeric(12,2) not null check(price >= 0),
  effective_from timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create table public.commission_rules (
  id uuid primary key default gen_random_uuid(),
  distributor_id uuid not null references public.distributors(id),
  product_id uuid not null references public.products(id),
  commission_type text not null check(commission_type in ('percentage','per_kg')),
  commission_value numeric(12,3) not null check(commission_value >= 0),
  effective_from timestamptz not null default now(),
  active boolean not null default true
);

create table public.stock_balances (
  distributor_id uuid not null references public.distributors(id),
  product_id uuid not null references public.products(id),
  quantity numeric(12,3) not null default 0 check(quantity >= 0),
  primary key(distributor_id,product_id)
);

create table public.stock_movements (
  id uuid primary key default gen_random_uuid(),
  distributor_id uuid not null references public.distributors(id),
  product_id uuid not null references public.products(id),
  movement_type text not null check(movement_type in ('receipt','sample','delivery','return','adjustment')),
  quantity numeric(12,3) not null check(quantity > 0),
  reference_id uuid,
  notes text,
  created_by uuid references public.profiles(id),
  created_at timestamptz not null default now()
);

create table public.cafes (
  id uuid primary key default gen_random_uuid(),
  distributor_id uuid not null references public.distributors(id),
  name text not null,
  contact_name text,
  phone text,
  address text,
  notes text,
  status text not null default 'prospect' check(status in ('prospect','interested','active','inactive')),
  created_at timestamptz not null default now()
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  distributor_id uuid not null references public.distributors(id),
  cafe_id uuid not null references public.cafes(id),
  order_date date not null default current_date,
  expected_delivery date,
  status text not null default 'pending' check(status in ('pending','confirmed','preparing','delivered','cancelled')),
  notes text,
  created_at timestamptz not null default now()
);

create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid not null references public.products(id),
  quantity numeric(12,3) not null check(quantity > 0)
);

create table public.samples (
  id uuid primary key default gen_random_uuid(),
  distributor_id uuid not null references public.distributors(id),
  cafe_id uuid not null references public.cafes(id),
  sample_date date not null default current_date,
  feedback text,
  notes text,
  marketing_cost numeric(12,2) not null default 0 check(marketing_cost >= 0),
  created_by uuid references public.profiles(id),
  created_at timestamptz not null default now()
);

create table public.sample_items (
  id uuid primary key default gen_random_uuid(),
  sample_id uuid not null references public.samples(id) on delete cascade,
  product_id uuid not null references public.products(id),
  quantity numeric(12,3) not null check(quantity > 0)
);

create table public.sales_invoices (
  id uuid primary key default gen_random_uuid(),
  invoice_number bigint generated by default as identity unique,
  order_id uuid unique not null references public.orders(id),
  distributor_id uuid not null references public.distributors(id),
  cafe_id uuid not null references public.cafes(id),
  invoice_date timestamptz not null default now(),
  total_amount numeric(12,2) not null check(total_amount >= 0),
  total_commission numeric(12,2) not null check(total_commission >= 0),
  company_net numeric(12,2) not null check(company_net >= 0),
  status text not null default 'issued' check(status in ('issued','void','credited'))
);

create table public.sales_invoice_items (
  id uuid primary key default gen_random_uuid(),
  invoice_id uuid not null references public.sales_invoices(id),
  product_id uuid not null references public.products(id),
  quantity numeric(12,3) not null,
  unit_price numeric(12,2) not null,
  line_total numeric(12,2) not null,
  commission_type text not null,
  commission_value numeric(12,3) not null,
  commission_amount numeric(12,2) not null,
  company_net numeric(12,2) not null
);

create table public.cafe_payments (
  id uuid primary key default gen_random_uuid(),
  cafe_id uuid not null references public.cafes(id),
  distributor_id uuid not null references public.distributors(id),
  amount numeric(12,2) not null check(amount > 0),
  received_by text not null check(received_by in ('distributor','company')),
  payment_method text not null default 'cash',
  payment_date timestamptz not null default now(),
  notes text,
  created_by uuid references public.profiles(id)
);

create table public.payment_allocations (
  id uuid primary key default gen_random_uuid(),
  payment_id uuid not null references public.cafe_payments(id),
  invoice_id uuid not null references public.sales_invoices(id),
  amount numeric(12,2) not null check(amount > 0),
  unique(payment_id,invoice_id)
);

create table public.distributor_remittances (
  id uuid primary key default gen_random_uuid(),
  distributor_id uuid not null references public.distributors(id),
  amount numeric(12,2) not null check(amount > 0),
  payment_method text not null default 'cash',
  remittance_date timestamptz not null default now(),
  reference_number text,
  notes text,
  received_by uuid references public.profiles(id)
);

create table public.remittance_allocations (
  id uuid primary key default gen_random_uuid(),
  remittance_id uuid not null references public.distributor_remittances(id),
  invoice_id uuid not null references public.sales_invoices(id),
  amount numeric(12,2) not null check(amount > 0),
  unique(remittance_id,invoice_id)
);

create table public.distributor_expenses (
  id uuid primary key default gen_random_uuid(),
  distributor_id uuid not null references public.distributors(id),
  expense_type text not null check(expense_type in ('sample','other')),
  amount numeric(12,2) not null check(amount >= 0),
  reference_id uuid,
  notes text,
  created_at timestamptz not null default now()
);

create index on public.cafes(distributor_id);
create index on public.orders(distributor_id,status);
create index on public.sales_invoices(distributor_id,cafe_id,invoice_date);
create index on public.stock_movements(distributor_id,product_id,created_at);
create index on public.cafe_payments(cafe_id,payment_date);

create or replace function public.current_distributor_id()
returns uuid language sql stable security definer set search_path=public
as $$ select id from public.distributors where user_id=auth.uid() and active=true limit 1 $$;
revoke all on function public.current_distributor_id() from public, anon;
grant execute on function public.current_distributor_id() to authenticated;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.profiles where id=auth.uid() and role='admin') $$;
revoke all on function public.is_admin() from public, anon;
grant execute on function public.is_admin() to authenticated;

