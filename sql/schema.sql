-- Admin receives stock into distributor custody.
create or replace function public.admin_receive_stock(p_distributor_id uuid,p_product_id uuid,p_quantity numeric,p_notes text default null)
returns void language plpgsql security definer set search_path=public
as $$
begin
 if not public.is_admin() then raise exception 'Admin only'; end if;
 if p_quantity<=0 then raise exception 'Quantity must be positive'; end if;
 insert into public.stock_balances(distributor_id,product_id,quantity)
 values(p_distributor_id,p_product_id,p_quantity)
 on conflict(distributor_id,product_id) do update set quantity=stock_balances.quantity+excluded.quantity;
 insert into public.stock_movements(distributor_id,product_id,movement_type,quantity,notes,created_by)
 values(p_distributor_id,p_product_id,'receipt',p_quantity,p_notes,auth.uid());
end $$;

-- Create a single-line order. Current MVP supports one product per order form.
create or replace function public.create_distributor_order(
 p_cafe_id uuid,p_distributor_id uuid,p_product_id uuid,p_quantity numeric,
 p_expected_delivery date default null,p_notes text default null
) returns uuid language plpgsql security definer set search_path=public
as $$
declare v_dist uuid; v_order uuid;
begin
 v_dist:=case when public.is_admin() then p_distributor_id else public.current_distributor_id() end;
 if v_dist is null then raise exception 'Distributor not found'; end if;
 if p_quantity<=0 then raise exception 'Quantity must be positive'; end if;
 if not exists(select 1 from public.cafes where id=p_cafe_id and distributor_id=v_dist) then raise exception 'Cafe is not assigned to this distributor'; end if;
 insert into public.orders(distributor_id,cafe_id,expected_delivery,notes,status)
 values(v_dist,p_cafe_id,p_expected_delivery,p_notes,'confirmed') returning id into v_order;
 insert into public.order_items(order_id,product_id,quantity) values(v_order,p_product_id,p_quantity);
 return v_order;
end $$;

-- Samples are marketing expenses and consume distributor custody stock.
create or replace function public.record_sample(p_cafe_id uuid,p_product_id uuid,p_quantity numeric,p_feedback text default null)
returns uuid language plpgsql security definer set search_path=public
as $$
declare v_dist uuid; v_sample uuid; v_cost numeric:=0;
begin
 v_dist:=public.current_distributor_id();
 if v_dist is null and public.is_admin() then
   select distributor_id into v_dist from public.cafes where id=p_cafe_id;
 end if;
 if v_dist is null or p_quantity<=0 then raise exception 'Invalid distributor or quantity'; end if;
 if not exists(select 1 from public.cafes where id=p_cafe_id and distributor_id=v_dist) then raise exception 'Cafe is not assigned to this distributor'; end if;
 update public.stock_balances set quantity=quantity-p_quantity
 where distributor_id=v_dist and product_id=p_product_id and quantity>=p_quantity;
 if not found then raise exception 'Insufficient stock'; end if;
 insert into public.samples(distributor_id,cafe_id,feedback,created_by)
 values(v_dist,p_cafe_id,p_feedback,auth.uid()) returning id into v_sample;
 insert into public.sample_items(sample_id,product_id,quantity) values(v_sample,p_product_id,p_quantity);
 insert into public.stock_movements(distributor_id,product_id,movement_type,quantity,reference_id,created_by)
 values(v_dist,p_product_id,'sample',p_quantity,v_sample,auth.uid());
 select coalesce(pp.price,0)*p_quantity into v_cost
 from public.product_prices pp where pp.product_id=p_product_id
 order by pp.effective_from desc limit 1;
 insert into public.distributor_expenses(distributor_id,expense_type,amount,reference_id,notes)
 values(v_dist,'sample',coalesce(v_cost,0),v_sample,'Marketing sample');
 return v_sample;
end $$;

-- Deliver order, deduct stock, snapshot current product price and distributor commission, issue invoice.
create or replace function public.deliver_order(p_order_id uuid)
returns uuid language plpgsql security definer set search_path=public
as $$
declare o public.orders%rowtype; it record; v_price numeric; v_type text; v_rate numeric; v_line numeric; v_comm numeric; v_net numeric; v_total numeric:=0; v_comm_total numeric:=0; v_invoice uuid;
begin
 select * into o from public.orders where id=p_order_id for update;
 if not found then raise exception 'Order not found'; end if;
 if not (public.is_admin() or o.distributor_id=public.current_distributor_id()) then raise exception 'Not authorized'; end if;
 if o.status not in ('confirmed','preparing') then raise exception 'Order is not deliverable'; end if;
 for it in select * from public.order_items where order_id=o.id loop
   update public.stock_balances set quantity=quantity-it.quantity
   where distributor_id=o.distributor_id and product_id=it.product_id and quantity>=it.quantity;
   if not found then raise exception 'Insufficient stock for product %',it.product_id; end if;
   select price into v_price from public.product_prices where product_id=it.product_id and effective_from<=now() order by effective_from desc limit 1;
   if v_price is null then raise exception 'No active product price'; end if;
   select commission_type,commission_value into v_type,v_rate
   from public.commission_rules where distributor_id=o.distributor_id and product_id=it.product_id and active=true and effective_from<=now()
   order by effective_from desc limit 1;
   if v_type is null then v_type:='percentage';v_rate:=0; end if;
   v_line:=round(it.quantity*v_price,2);
   v_comm:=case when v_type='percentage' then round(v_line*v_rate/100,2) else round(it.quantity*v_rate,2) end;
   if v_comm>v_line then raise exception 'Commission cannot exceed line total'; end if;
   v_net:=v_line-v_comm;
   v_total:=v_total+v_line;v_comm_total:=v_comm_total+v_comm;
 end loop;
 insert into public.sales_invoices(order_id,distributor_id,cafe_id,total_amount,total_commission,company_net)
 values(o.id,o.distributor_id,o.cafe_id,v_total,v_comm_total,v_total-v_comm_total)
 returning id into v_invoice;
 for it in select * from public.order_items where order_id=o.id loop
   select price into v_price from public.product_prices where product_id=it.product_id and effective_from<=now() order by effective_from desc limit 1;
   select commission_type,commission_value into v_type,v_rate from public.commission_rules where distributor_id=o.distributor_id and product_id=it.product_id and active=true and effective_from<=now() order by effective_from desc limit 1;
   if v_type is null then v_type:='percentage';v_rate:=0; end if;
   v_line:=round(it.quantity*v_price,2);
   v_comm:=case when v_type='percentage' then round(v_line*v_rate/100,2) else round(it.quantity*v_rate,2) end;
   insert into public.sales_invoice_items(invoice_id,product_id,quantity,unit_price,line_total,commission_type,commission_value,commission_amount,company_net)
   values(v_invoice,it.product_id,it.quantity,v_price,v_line,v_type,v_rate,v_comm,v_line-v_comm);
   insert into public.stock_movements(distributor_id,product_id,movement_type,quantity,reference_id,created_by)
   values(o.distributor_id,it.product_id,'delivery',it.quantity,o.id,auth.uid());
 end loop;
 update public.orders set status='delivered' where id=o.id;
 return v_invoice;
end $$;

-- Record a payment collected by the distributor or company. Allocation is FIFO.
create or replace function public.record_cafe_payment(
 p_cafe_id uuid,p_amount numeric,p_payment_method text default 'cash',p_received_by text default 'distributor'
) returns uuid language plpgsql security definer set search_path=public
as $$
declare v_dist uuid; v_payment uuid; v_left numeric:=p_amount; inv record; v_due numeric; v_alloc numeric; v_paid numeric;
begin
 if p_amount<=0 then raise exception 'Amount must be positive'; end if;
 if p_received_by not in ('distributor','company') then raise exception 'Invalid receiver'; end if;
 select distributor_id into v_dist from public.cafes where id=p_cafe_id;
 if v_dist is null then raise exception 'Cafe not found'; end if;
 if not (public.is_admin() or v_dist=public.current_distributor_id()) then raise exception 'Not authorized'; end if;
 insert into public.cafe_payments(cafe_id,distributor_id,amount,received_by,payment_method,created_by)
 values(p_cafe_id,v_dist,p_amount,p_received_by,p_payment_method,auth.uid()) returning id into v_payment;
 for inv in select * from public.sales_invoices where cafe_id=p_cafe_id and status='issued' order by invoice_date for update loop
   select coalesce(sum(pa.amount),0) into v_paid from public.payment_allocations pa where pa.invoice_id=inv.id;
   v_due:=inv.total_amount-v_paid;
   if v_due>0 and v_left>0 then
     v_alloc:=least(v_due,v_left);
     insert into public.payment_allocations(payment_id,invoice_id,amount) values(v_payment,inv.id,v_alloc);
     v_left:=v_left-v_alloc;
   end if;
 end loop;
 if v_left>0 then raise exception 'Payment exceeds outstanding invoices by %',v_left; end if;
 return v_payment;
end $$;

-- Distributor remits company net proceeds, capped by collected money less commission entitlement.
create or replace function public.record_distributor_remittance(
 p_distributor_id uuid,p_amount numeric,p_payment_method text default 'cash',p_reference text default null,p_notes text default null
) returns uuid language plpgsql security definer set search_path=public
as $$
declare v_dist uuid; v_id uuid; v_left numeric:=p_amount; inv record; v_collected numeric; v_remitted numeric; v_cap numeric; v_alloc numeric;
begin
 if public.is_admin() then v_dist:=p_distributor_id; else v_dist:=public.current_distributor_id(); end if;
 if v_dist is null then raise exception 'Distributor not found or not authorized'; end if;
 if not exists(select 1 from public.distributors where id=v_dist and active=true) then raise exception 'Distributor is inactive or not found'; end if;
 if p_amount<=0 then raise exception 'Amount must be positive'; end if;
 select coalesce(sum(pa.amount),0) into v_collected
 from public.payment_allocations pa join public.cafe_payments cp on cp.id=pa.payment_id
 where cp.distributor_id=v_dist and cp.received_by='distributor';
 select coalesce(sum(ra.amount),0) into v_remitted
 from public.remittance_allocations ra join public.distributor_remittances dr on dr.id=ra.remittance_id
 where dr.distributor_id=v_dist;
 v_cap:=v_collected-v_remitted;
 if p_amount>v_cap then raise exception 'Remittance exceeds unremitted collections'; end if;
 insert into public.distributor_remittances(distributor_id,amount,payment_method,reference_number,notes,received_by)
 values(v_dist,p_amount,p_payment_method,p_reference,p_notes,auth.uid()) returning id into v_id;
 for inv in
   select si.id,coalesce(sum(pa.amount) filter (where cp.received_by='distributor'),0) collected,si.company_net
   from public.sales_invoices si
   left join public.payment_allocations pa on pa.invoice_id=si.id
   left join public.cafe_payments cp on cp.id=pa.payment_id
   where si.distributor_id=v_dist
   group by si.id,si.company_net
   order by si.id
 loop
   exit when v_left<=0;
   select coalesce(sum(ra.amount),0) into v_remitted from public.remittance_allocations ra where ra.invoice_id=inv.id;
   v_cap:=greatest(least(inv.collected,inv.company_net)-v_remitted,0);
   if v_cap>0 then
     v_alloc:=least(v_cap,v_left);
     insert into public.remittance_allocations(remittance_id,invoice_id,amount) values(v_id,inv.id,v_alloc);
     v_left:=v_left-v_alloc;
   end if;
 end loop;
 return v_id;
end $$;

